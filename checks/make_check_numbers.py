"""LaTeX macros for the numbers that come from the checks in this folder.

Writes paper/numbers_checks.tex. Every value is computed here with the model
in pqemv/; nothing is typed in.

Run: python checks/make_check_numbers.py [--check]
"""
import os
import sys
from decimal import Decimal, ROUND_HALF_UP
from fractions import Fraction as F
from math import ceil

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "analyses")); sys.path.insert(0, os.path.join(ROOT, "tests"))
sys.path.insert(0, os.path.join(ROOT, "checks"))

import run as R                                        # noqa: E402
import kernel8_rmin as S                               # noqa: E402
from pqemv import architectures as ar                  # noqa: E402
from pqemv import implementations as cat                     # noqa: E402
from pqemv.transport import Link, closed_form          # noqa: E402
import record_packing as P                             # noqa: E402
import type_b as TB                                    # noqa: E402

ETU = F(128, 13_560_000)
FRAMES = sum((S.wupb_time() if n.startswith("WUPB") else e * ETU)
             for n, b, e, g, c, k in S.TERMS if not n.startswith("t_P"))
GAPS = sum(g for n, b, e, g, c, k in S.TERMS if not n.startswith("t_P")) * S.GAP
RMIN = FRAMES + GAPS
WAITS = 2 * S.T_P


def d1(x):
    """One decimal, half up, from an exact fraction."""
    x = F(x)
    return str((Decimal(x.numerator) / Decimal(x.denominator)).quantize(Decimal("0.1"), ROUND_HALF_UP))


def reader_fixed(arch, sig, kem, fs, extended=False):
    ex, _, _ = R.build(arch, sig, kem, 2, extended=extended)
    link = Link(fsd=fs, fsc=fs)
    tot = closed_form(ex, link)
    return tot.reader_frames + tot.pcd_gaps * link.t_fdt_pcd, tot.reader_frames


def build():
    m = []
    enc = cat.reader_cycles("ML-KEM-512", "encaps")
    # extended-length APDUs, 512-byte frames, with R_min and both waits
    fixed, _ = reader_fixed("C-min", "FN-DSA-512", "ML-KEM-512", 512, extended=True)
    total = (fixed + RMIN + WAITS) * 1000
    m.append(("ExtCminTotalMs", d1(total), "ms", "checks/extended_apdus.py (FSD=FSC 512)"))
    m.append(("ExtCminLeftMs", d1(R.READER_BUDGET * 1000 - total), "ms", "checks/extended_apdus.py"))
    # certificate checks after the removal signal: encapsulation only
    for fs, name in ((256, "EncapsOnlyClockMinMHz"), (512, "EncapsOnlyClockFiveTwelveMHz")):
        _, frames_only = reader_fixed("C-min", "FN-DSA-512", "ML-KEM-512", fs)
        left = R.READER_BUDGET - frames_only - FRAMES
        m.append((name, d1(F(ceil(F(enc) / left), 10 ** 6)), "MHz", "checks/reader_after_removal.py"))
    # shared records
    model, _ = reader_fixed("C-min", "FN-DSA-512", "ML-KEM-512", 512)
    P.ar.cert_exchanges = P.patched
    packed, _ = reader_fixed("C-min", "FN-DSA-512", "ML-KEM-512", 512)
    P.ar.cert_exchanges = P.orig
    m.append(("PackedSavedReaderMs", d1((model - packed) * 1000), "ms", "checks/record_packing.py"))
    m.append(("PackedMarginMs", d1((R.READER_BUDGET - packed - RMIN) * 1000), "ms", "checks/record_packing.py"))
    m.append(("PackedMarginTpMs", d1((R.READER_BUDGET - packed - RMIN - WAITS) * 1000), "ms", "checks/record_packing.py"))
    # Book 2 certificate layout (D-C1b) against the Book E layout (D-C1), bytes saved
    sig = cat.SIZES["FN-DSA-512"]
    m.append(("FmtBIssuerSavedBytes", str(ar.pq_issuer_cert(sig, "E") - ar.pq_issuer_cert(sig, "B")), "B", "pqemv/architectures.py pq_issuer_cert"))
    m.append(("FmtBIccSavedBytes", str(ar.pq_icc_cert(sig, 800, "E") - ar.pq_icc_cert(sig, 800, "B")), "B", "pqemv/architectures.py pq_icc_cert"))
    # Type B frames: C-min authentication exchanges alone, 512-byte frames
    m.append(("TypeBAuthFiveTwelveMs", d1(TB.c_min_b(512).reader() * 1000), "ms", "checks/type_b.py"))
    # smallest ML-DSA-44 signer that runs on SC300/SC000, in 1024-byte KB
    m0 = cat.LIT["m0plus"]["ML-DSA-44"]
    smallest = F(m0["sign_stack_kb"]) * 1024 + cat.SIZES["ML-DSA-44"]["sig"] + 32 + 261
    m.append(("MlFourSmallestRamKiB", d1(smallest / 1024), "KB", "M0+ PQClean stack + buffers, 1024-byte KB"))
    m.append(("MlFourRamRatioKiB", d1(smallest / (16 * 1024)), "", "smallest / 16 KB (1024-byte KB)"))
    return m


def render(m):
    lines = ["% Generated by checks/make_check_numbers.py -- do not edit."]
    for name, val, units, src in m:
        val = val.replace("-", "\\ensuremath{-}", 1) if val.startswith("-") else val
        lines.append("\\newcommand{\\%s}{%s}%% %s  %s" % (name, val, units, src))
    return "\n".join(lines) + "\n"


def main():
    text = render(build())
    path = os.path.join(ROOT, "paper", "numbers_checks.tex")
    if "--check" in sys.argv:
        if not os.path.exists(path) or open(path, encoding="utf-8").read() != text:
            raise SystemExit("paper/numbers_checks.tex differs from a fresh regeneration")
        print("check macros: regenerated identically")
        return
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(text, end="")


if __name__ == "__main__":
    main()
